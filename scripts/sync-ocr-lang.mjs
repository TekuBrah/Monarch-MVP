#!/usr/bin/env node
/**
 * Put the OCR language model where Tesseract can ask for it by name.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS SCRIPT EXISTS, WHICH IS NOT THE REASON IT LOOKS LIKE.
 *
 * The obvious way to serve this file from our own origin is a Vite `?url`
 * import, which is exactly how the OCR worker and the WebAssembly engine are
 * served (see `src/data/ocr/recognise.ts`). It does not work for the language
 * model, and the reason is a naming convention rather than a delivery problem:
 *
 *   Tesseract's `langPath` is a DIRECTORY. The worker appends
 *   `<lang>.traineddata.gz` to it and fetches that. A `?url` asset has a
 *   CONTENT HASH in its filename, so there is no directory anywhere in `dist/`
 *   holding a file called `eng.traineddata.gz`.
 *
 * THE DOCUMENTED ALTERNATIVE IS BROKEN UPSTREAM IN TESSERACT.JS 7.0.0, and it
 * was tried first. `createWorker` accepts `Lang[]` — `{ code, data }` — so the
 * bytes can be handed over directly with no path at all. `loadLanguage` reads
 * `l.code` correctly and writes the model to the virtual filesystem; but
 * `initialize` in the same file reads `l.data`:
 *
 *   src/worker-script/index.js  loadLanguage:  typeof l === 'string' ? l : l.code
 *   src/worker-script/index.js  initialize:    typeof l === 'string' ? l : l.data
 *
 * So the engine is initialised with the raw Uint8Array stringified as its
 * language NAME. Measured in the browser at Gate 50-B — Tesseract reports
 * `Error opening data file ./24,0,0,0,255,255,255,...` and then
 * `Tesseract couldn't load any languages!`, and `createWorker` rejects with
 * `initialization failed`. The model had loaded fine; only the name was wrong.
 *
 * `langPath` is therefore the supported route, and a stable path is what it
 * needs. Hence this copy.
 * ─────────────────────────────────────────────────────────────────────────────
 * THE DESTINATION IS GITIGNORED, DELIBERATELY.
 *
 * `public/` is Vite's verbatim-copy directory, so anything here is deployed —
 * which is what makes it the right destination. But the file is 2.82 MB of
 * binary whose provenance is entirely the pinned `@tesseract.js-data/eng`
 * version, so committing it would put a second copy of that model in this
 * repo's history with nothing keeping the two in step. Generated from the
 * dependency, on demand, is the same relationship the OCR worker and engine
 * already have — they are just generated by Vite instead of by this.
 *
 * IT MUST RUN BEFORE ANYTHING SERVES OR BUILDS THE APP, which is why it is
 * wired as a `pre` hook on `dev`, `build`, `build:package` and both suite
 * scripts in `package.json`. Netlify runs `npm run build:package`, so the
 * deploy is covered by the same hook.
 *
 * A MISSING FILE FAILS LOUDLY RATHER THAN SILENTLY: `e2e/ocr.spec.ts` asserts
 * that the model was actually fetched, so a skipped sync reddens the suite
 * instead of degrading OCR quietly.
 * ─────────────────────────────────────────────────────────────────────────────
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/**
 * `4.0.0_best_int` AND NOT `4.0.0`, and the difference is 8 MB.
 *
 * The package ships two models. `4.0.0` (10.4 MB) carries BOTH the legacy and
 * the LSTM engines; `4.0.0_best_int` (2.82 MB) carries only the LSTM one. The
 * app initialises Tesseract with LSTM_ONLY and never calls `worker.detect`,
 * which is the only thing that needs the legacy model — so the larger file
 * would be 7.6 MB of model that cannot be reached.
 *
 * It is also what Tesseract's own default would fetch for an LSTM-only worker,
 * so this is the same model the library would have chosen, served from here.
 */
const SOURCE = path.join(
  ROOT,
  'node_modules',
  '@tesseract.js-data',
  'eng',
  '4.0.0_best_int',
  'eng.traineddata.gz',
)

/**
 * The name is dictated by Tesseract, not chosen. `langPath` is `/ocr`, and the
 * worker appends `<lang>.traineddata.gz` — so renaming either half breaks the
 * fetch, and `recognise.ts` names the same directory.
 */
const DEST_DIR = path.join(ROOT, 'public', 'ocr')
const DEST = path.join(DEST_DIR, 'eng.traineddata.gz')

if (!fs.existsSync(SOURCE)) {
  console.error('FAIL — the OCR language model is not installed:')
  console.error(`  ${path.relative(ROOT, SOURCE)}`)
  console.error('')
  console.error('It ships in the `@tesseract.js-data/eng` package, which is a')
  console.error('pinned dependency. Run `npm install` and try again.')
  process.exit(1)
}

const source = fs.readFileSync(SOURCE)

// IDEMPOTENT, AND COMPARED BY CONTENT RATHER THAN BY TIMESTAMP. This runs
// before every dev server start and every build, so it has to be cheap and it
// must not rewrite an identical file — a needless write would change the
// mtime and, on some setups, re-trigger a watcher mid-run.
if (fs.existsSync(DEST) && fs.readFileSync(DEST).equals(source)) {
  console.log(
    `ocr language model already current — public/ocr/eng.traineddata.gz (${source.length} bytes)`,
  )
  process.exit(0)
}

fs.mkdirSync(DEST_DIR, { recursive: true })
fs.writeFileSync(DEST, source)
console.log(
  `ocr language model synced -> public/ocr/eng.traineddata.gz (${source.length} bytes)`,
)
